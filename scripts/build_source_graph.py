"""Render SOURCE_GRAPH.md from data/source-graph.json.

Usage: python3 scripts/build_source_graph.py
Level = shortest distance from the root (the LLMeter website, level 0).
"""
import json
from collections import deque
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAX_LEVEL = 5

data = json.loads((ROOT / "data" / "source-graph.json").read_text())
nodes = {n["id"]: n for n in data["nodes"]}
out = {}
for e in data["edges"]:
    out.setdefault(e["from"], []).append(e)

level = {data["root"]: 0}
q = deque([data["root"]])
while q:
    cur = q.popleft()
    for e in out.get(cur, []):
        if e["to"] not in level:
            level[e["to"]] = level[cur] + 1
            q.append(e["to"])

missing = set(nodes) - set(level)
assert not missing, f"unreachable nodes: {missing}"
assert max(level.values()) <= MAX_LEVEL, "graph deeper than 5 levels"


def label(n):
    t = n["title"].replace('"', "'")
    return t if len(t) <= 48 else t[:45] + "..."


def mid(i):
    return i.replace("-", "_")


lines = ["```mermaid", "graph LR"]
for lv in range(MAX_LEVEL + 1):
    ids = [i for i in nodes if level[i] == lv]
    if not ids:
        continue
    lines.append(f'  subgraph L{lv}["Level {lv}"]')
    for i in ids:
        lines.append(f'    {mid(i)}["{label(nodes[i])}"]')
    lines.append("  end")
for e in data["edges"]:
    lines.append(f'  {mid(e["from"])} --> {mid(e["to"])}')
for i, n in nodes.items():
    s = n["status"]
    cls = "expanded" if s == "expanded" else "primary" if s.startswith("primary") else "stopped"
    lines.append(f"  class {mid(i)} {cls}")
lines += [
    "  classDef expanded fill:#dbeafe,stroke:#1d4ed8,color:#0b1b3f",
    "  classDef primary fill:#dcfce7,stroke:#15803d,color:#052e16",
    "  classDef stopped fill:#f3f4f6,stroke:#9ca3af,color:#374151,stroke-dasharray: 4 3",
    "```",
]

md = [
    "# Source graph",
    "",
    "Where LLMeter's sources get their information, traced up to five levels deep.",
    "",
    "- **Level 0** is the LLMeter website. **Level 1** is the sources listed in [RESOURCES.md](RESOURCES.md).",
    "- Each arrow points from a source to a source it cites or draws data from. Repeated sources are merged into one node, and a node sits at the shortest level it is reached from.",
    f"- Pages were read on {data['read_on']}. Nodes marked *not opened* are named by the source above them but were not read themselves.",
    "- Blue nodes were expanded. Green nodes are primary data (a survey, a spec sheet, original tasks or questions), so there is nothing further to trace. Grey dashed nodes were not expanded, and the table says why.",
    "",
    "Data: [data/source-graph.json](data/source-graph.json). This file is generated by `python3 scripts/build_source_graph.py`; edit the JSON, not this file.",
    "",
    "## Diagram",
    "",
    *lines,
    "",
    "## Nodes by level",
    "",
]
cited_by = {}
for e in data["edges"]:
    cited_by.setdefault(e["to"], []).append(e["from"])
for lv in range(MAX_LEVEL + 1):
    ids = [i for i in nodes if level[i] == lv]
    if not ids:
        continue
    md += [f"### Level {lv} ({len(ids)})", "", "| Source | Publisher | Reached from | Read | Status |", "| --- | --- | --- | --- | --- |"]
    for i in ids:
        n = nodes[i]
        t = f"[{n['title']}]({n['url']})" if n["url"] else n["title"]
        frm = ", ".join(nodes[f]["title"] for f in cited_by.get(i, []) if level[f] < lv) or "-"
        rd = n["read"] or "not opened"
        md.append(f"| {t} | {n['publisher'] or '-'} | {frm} | {rd} | {n['status']} |")
    md.append("")

deep = [i for i in nodes if level[i] == MAX_LEVEL]
md += [
    "## Where the graph stops",
    "",
    f"- {len(deep)} chains reach level 5. Below that the graph is cut off on purpose.",
    "- Many branches end earlier because they reach primary data (government surveys, manufacturer specs, original benchmark tasks), which has no further source.",
    "- Others stop because the source names a reference without a link (press reports, market reports, review sites), the reference is paywalled (BloombergNEF), or Artificial Analysis gives no origin (CritPt).",
    "- Software (runtimes, evaluation platforms, analysis code) is shown as a node but not traced further, since it is a tool rather than a source of facts.",
    "",
]
(ROOT / "SOURCE_GRAPH.md").write_text("\n".join(md))
print({lv: sum(1 for v in level.values() if v == lv) for lv in range(MAX_LEVEL + 1)})
